"""Physical realizability checks for Mueller matrices.

The polynomial expressions in this module intentionally mirror the original
notebook implementation so experiment results stay reproducible.
"""

import numpy as np

__all__ = [
    "build_eigen_matrix",
    "cholesky_realizable",
    "choletsky",
    "charpoly",
    "charpoly_vectorized",
]


def build_eigen_matrix(M):
    """Build the coherency matrix H(M) from a measured Mueller matrix.

    Args:
        M: The measured Mueller matrix.

    Returns:
        The coherency matrix H(M).
    """

    H = np.zeros((4, 4), dtype=np.complex128)

    H[0, 0] = M[0, 0] + M[0, 1] + M[1, 0] + M[1, 1]
    H[0, 1] = M[0, 2] + M[1, 2] + 1j * (M[0, 3] + M[1, 3])
    H[0, 2] = M[2, 0] + M[2, 1] - 1j * (M[3, 0] + M[3, 1])
    H[0, 3] = M[2, 2] + M[3, 3] + 1j * (M[2, 3] - M[3, 2])

    H[1, 0] = np.conj(H[0, 1])
    H[1, 1] = M[0, 0] - M[0, 1] + M[1, 0] - M[1, 1]
    H[1, 2] = M[2, 2] - M[3, 3] - 1j * (M[2, 3] + M[3, 2])
    H[1, 3] = M[2, 0] - M[2, 1] - 1j * (M[3, 0] - M[3, 1])

    H[2, 0] = np.conj(H[0, 2])
    H[2, 1] = np.conj(H[1, 2])
    H[2, 2] = M[0, 0] + M[0, 1] - M[1, 0] - M[1, 1]
    H[2, 3] = M[0, 2] - M[1, 2] + 1j * (M[0, 3] - M[1, 3])

    H[3, 0] = np.conj(H[0, 3])
    H[3, 1] = np.conj(H[1, 3])
    H[3, 2] = np.conj(H[2, 3])
    H[3, 3] = M[0, 0] - M[0, 1] - M[1, 0] + M[1, 1]

    return H


def cholesky_realizable(M):
    """Return ``True`` when the matrix passes a Cholesky-based PR check."""
    H = build_eigen_matrix(M)
    try:
        np.linalg.cholesky(H)
        return True
    except np.linalg.LinAlgError:
        return False


def choletsky(M):
    """Backward-compatible alias of :func:`cholesky_realizable`."""
    return cholesky_realizable(M)


