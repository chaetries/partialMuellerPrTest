def charpoly(M, verbose=False):
    C1 = M[0, 0]

    C2 = (3 * M[0, 0]**2 - M[0, 1]**2 - M[0, 2]**2 - M[0, 3]**2 -
          M[1, 0]**2 - M[1, 1]**2 - M[1, 2]**2 - M[1, 3]**2 -
          M[2, 0]**2 - M[2, 1]**2 - M[2, 2]**2 - M[2, 3]**2 -
          M[3, 0]**2 - M[3, 1]**2 - M[3, 2]**2 - M[3, 3]**2)

    C3 = (4 * M[0, 0]**3 +
          (-4 * M[0, 1]**2 - 4 * M[0, 2]**2 - 4 * M[0, 3]**2 -
           -4 * M[1, 0]**2 - 4 * M[1, 1]**2 - 4 * M[1, 2]**2 - 4 * M[1, 3]**2 -
           -4 * M[2, 0]**2 - 4 * M[2, 1]**2 - 4 * M[2, 2]**2 - 4 * M[2, 3]**2 -
           -4 * M[3, 0]**2 - 4 * M[3, 1]**2 - 4 * M[3, 2]**2 - 4 * M[3, 3]**2) * M[0, 0] +
          (8 * M[1, 0] * M[1, 1] + 8 * M[2, 0] * M[2, 1] + 8 * M[3, 0] * M[3, 1]) * M[0, 1] +
          (8 * M[1, 0] * M[1, 2] + 8 * M[2, 0] * M[2, 2] + 8 * M[3, 0] * M[3, 2]) * M[0, 2] +
          (8 * M[1, 0] * M[1, 3] + 8 * M[2, 0] * M[2, 3] + 8 * M[3, 0] * M[3, 3]) * M[0, 3] +
          (8 * M[2, 2] * M[3, 3] - 8 * M[2, 3] * M[3, 2]) * M[1, 1] +
          (-8 * M[2, 1] * M[3, 3] + 8 * M[2, 3] * M[3, 1]) * M[1, 2] +
          8 * M[1, 3] * (M[2, 1] * M[3, 2] - M[2, 2] * M[3, 1]))

    C4 = (M[0, 0]**4 + M[0, 1]**4 + M[0, 2]**4 + M[1, 0]**4 +
          M[1, 1]**4 + M[1, 2]**4 + M[2, 0]**4 + M[2, 1]**4 +
          M[2, 2]**4 + M[0, 3]**4 + M[1, 3]**4 + M[2, 3]**4 +
          8 * M[2, 2] * M[2, 3] * M[3, 2] * M[3, 3] -
          8 * M[3, 0] * (M[2, 1] * M[3, 1] + M[2, 2] * M[3, 2] + M[2, 3] * M[3, 3]) * M[2, 0] +
          8 * M[3, 1] * (M[2, 2] * M[3, 2] + M[2, 3] * M[3, 3]) * M[2, 1] +
          8 * M[1, 3] * (M[2, 2] * M[2, 3] + M[3, 2] * M[3, 3]) * M[1, 2] +
          (M[3, 0]**2 - M[3, 1]**2 - M[3, 2]**2 - M[3, 3]**2)**2 +
          (2 * M[3, 0]**2 - 2 * M[3, 1]**2 - 2 * M[3, 2]**2 + 2 * M[3, 3]**2) * M[2, 3]**2 +
          (2 * M[2, 3]**2 + 2 * M[3, 0]**2 - 2 * M[3, 1]**2 + 2 * M[3, 2]**2 - 2 * M[3, 3]**2) * M[2, 2]**2 +
          (2 * M[2, 2]**2 + 2 * M[2, 3]**2 + 2 * M[3, 0]**2 + 2 * M[3, 1]**2 - 2 * M[3, 2]**2 - 2 * M[3, 3]**2) * M[2, 1]**2 +
          (-2 * M[2, 1]**2 - 2 * M[2, 2]**2 - 2 * M[2, 3]**2 + 2 * M[3, 0]**2 + 2 * M[3, 1]**2 + 2 * M[3, 2]**2 + 2 * M[3, 3]**2) * M[2, 0]**2 +
          (2 * M[2, 0]**2 - 2 * M[2, 1]**2 - 2 * M[2, 2]**2 + 2 * M[2, 3]**2 + 2 * M[3, 0]**2 - 2 * M[3, 1]**2 - 2 * M[3, 2]**2 + 2 * M[3, 3]**2) * M[1, 3]**2 +
          (2 * M[1, 3]**2 + 2 * M[2, 0]**2 - 2 * M[2, 1]**2 + 2 * M[2, 2]**2 - 2 * M[2, 3]**2 + 2 * M[3, 0]**2 - 2 * M[3, 1]**2 + 2 * M[3, 2]**2 - 2 * M[3, 3]**2) * M[1, 2]**2 +
          ((8 * M[2, 1] * M[2, 2] + 8 * M[3, 1] * M[3, 2]) * M[1, 2] +
          8 * M[1, 3] * (M[2, 1] * M[2, 3] + M[3, 1] * M[3, 3])) * M[1, 1] +
          (2 * M[1, 2]**2 + 2 * M[1, 3]**2 + 2 * M[2, 0]**2 + 2 * M[2, 1]**2 - 2 * M[2, 2]**2 - 2 * M[2, 3]**2 + 2 * M[3, 0]**2 + 2 * M[3, 1]**2 - 2 * M[3, 2]**2 - 2 * M[3, 3]**2) * M[1, 1]**2 +
          ((-8 * M[2, 0] * M[2, 1] - 8 * M[3, 0] * M[3, 1]) * M[1, 1] + (-8 * M[2, 0] * M[2, 2] - 8 * M[3, 0] * M[3, 2]) * M[1, 2] -
          8 * M[1, 3] * (M[2, 0] * M[2, 3] + M[3, 0] * M[3, 3])) * M[1, 0] +
          (-2 * M[1, 1]**2 - 2 * M[1, 2]**2 - 2 * M[1, 3]**2 + 2 * M[2, 0]**2 + 2 * M[2, 1]**2 + 2 * M[2, 2]**2 + 2 * M[2, 3]**2 + 2 * M[3, 0]**2 + 2 * M[3, 1]**2 + 2 * M[3, 2]**2 + 2 * M[3, 3]**2) * M[1, 0]**2 +
          ((-8 * M[2, 1] * M[3, 2] + 8 * M[2, 2] * M[3, 1]) * M[1, 0] +
          (8 * M[2, 0] * M[3, 2] - 8 * M[2, 2] * M[3, 0]) * M[1, 1] +
          8 * M[1, 2] * (-M[2, 0] * M[3, 1] + M[2, 1] * M[3, 0])) * M[0, 3] +
          (-2 * M[1, 0]**2 + 2 * M[1, 1]**2 + 2 * M[1, 2]**2 - 2 * M[1, 3]**2 - 2 * M[2, 0]**2 + 2 * M[2, 1]**2 + 2 * M[2, 2]**2 - 2 * M[2, 3]**2 - 2 * M[3, 0]**2 + 2 * M[3, 1]**2 + 2 * M[3, 2]**2 - 2 * M[3, 3]**2) * M[0, 3]**2 +
          ((-8 * M[1, 2] * M[1, 3] - 8 * M[2, 2] * M[2, 3] - 8 * M[3, 2] * M[3, 3]) * M[0, 3] +
          (8 * M[2, 1] * M[3, 3] - 8 * M[2, 3] * M[3, 1]) * M[1, 0] +
          (-8 * M[2, 0] * M[3, 3] + 8 * M[2, 3] * M[3, 0]) * M[1, 1] -
          8 * M[1, 3] * (-M[2, 0] * M[3, 1] + M[2, 1] * M[3, 0])) * M[0, 2] +
          (2 * M[0, 3]**2 - 2 * M[1, 0]**2 + 2 * M[1, 1]**2 - 2 * M[1, 2]**2 + 2 * M[1, 3]**2 - 2 * M[2, 0]**2 + 2 * M[2, 1]**2 - 2 * M[2, 2]**2 + 2 * M[2, 3]**2 - 2 * M[3, 0]**2 + 2 * M[3, 1]**2 - 2 * M[3, 2]**2 + 2 * M[3, 3]**2) * M[0, 2]**2 +
          ((-8 * M[1, 1] * M[1, 2] - 8 * M[2, 1] * M[2, 2] - 8 * M[3, 1] * M[3, 2]) * M[0, 2] +
          (-8 * M[1, 1] * M[1, 3] - 8 * M[2, 1] * M[2, 3] - 8 * M[3, 1] * M[3, 3]) * M[0, 3] +
          (-8 * M[2, 2] * M[3, 3] + 8 * M[2, 3] * M[3, 2]) * M[1, 0] +
          (8 * M[2, 0] * M[3, 3] - 8 * M[2, 3] * M[3, 0]) * M[1, 2] +
          8 * M[1, 3] * (-M[2, 0] * M[3, 2] + M[2, 2] * M[3, 0])) * M[0, 1] +
          (2 * M[0, 2]**2 + 2 * M[0, 3]**2 - 2 * M[1, 0]**2 - 2 * M[1, 1]**2 + 2 * M[1, 2]**2 + 2 * M[1, 3]**2 - 2 * M[2, 0]**2 - 2 * M[2, 1]**2 + 2 * M[2, 2]**2 + 2 * M[2, 3]**2 - 2 * M[3, 0]**2 - 2 * M[3, 1]**2 + 2 * M[3, 2]**2 + 2 * M[3, 3]**2) * M[0, 1]**2 +
          ((8 * M[1, 0] * M[1, 1] + 8 * M[2, 0] * M[2, 1] + 8 * M[3, 0] * M[3, 1]) * M[0, 1] +
          (8 * M[1, 0] * M[1, 2] + 8 * M[2, 0] * M[2, 2] + 8 * M[3, 0] * M[3, 2]) * M[0, 2] +
          (8 * M[1, 0] * M[1, 3] + 8 * M[2, 0] * M[2, 3] + 8 * M[3, 0] * M[3, 3]) * M[0, 3] +
          (8 * M[2, 2] * M[3, 3] - 8 * M[2, 3] * M[3, 2]) * M[1, 1] +
          (-8 * M[2, 1] * M[3, 3] + 8 * M[2, 3] * M[3, 1]) * M[1, 2] +
          8 * M[1, 3] * (M[2, 1] * M[3, 2] - M[2, 2] * M[3, 1])) * M[0, 0] +
          (-2 * M[0, 1]**2 - 2 * M[0, 2]**2 - 2 * M[0, 3]**2 - 2 * M[1, 0]**2 -
          2 * M[1, 1]**2 - 2 * M[1, 2]**2 - 2 * M[1, 3]**2 - 2 * M[2, 0]**2 -
          2 * M[2, 1]**2 - 2 * M[2, 2]**2 - 2 * M[2, 3]**2 - 2 * M[3, 0]**2 -
          2 * M[3, 1]**2 - 2 * M[3, 2]**2 - 2 * M[3, 3]**2) * M[0, 0]**2)
    if verbose:
        print(f"C1: {C1}")
        print(f"C2: {C2}")
        print(f"C3: {C3}")
        print(f"C4: {C4}")

    return ((C1 >= 0) and (C2 >= 0) and (C3 >= 0) and (C4 >= 0))


def charpoly_vectorized(M_batch, verbose=False):
    """
    Vectorized version of charpoly that processes multiple 4x4 matrices at once.

    Args:
        M_batch: Array of shape (N, 4, 4) where N is the number of matrices
        verbose: Whether to print coefficient values

    Returns:
        Boolean array of shape (N,) indicating physical realizability
    """
    # Extract all matrix elements at once - shape (N,)
    M00, M01, M02, M03 = M_batch[:, 0, 0], M_batch[:, 0, 1], M_batch[:, 0, 2], M_batch[:, 0, 3]
    M10, M11, M12, M13 = M_batch[:, 1, 0], M_batch[:, 1, 1], M_batch[:, 1, 2], M_batch[:, 1, 3]
    M20, M21, M22, M23 = M_batch[:, 2, 0], M_batch[:, 2, 1], M_batch[:, 2, 2], M_batch[:, 2, 3]
    M30, M31, M32, M33 = M_batch[:, 3, 0], M_batch[:, 3, 1], M_batch[:, 3, 2], M_batch[:, 3, 3]

    # Compute C1 for all matrices at once
    C1 = M00

    # Compute C2 for all matrices at once
    C2 = (3 * M00 ** 2 - M01 ** 2 - M02 ** 2 - M03 ** 2 -
          M10 ** 2 - M11 ** 2 - M12 ** 2 - M13 ** 2 -
          M20 ** 2 - M21 ** 2 - M22 ** 2 - M23 ** 2 -
          M30 ** 2 - M31 ** 2 - M32 ** 2 - M33 ** 2)

    # Compute C3 for all matrices at once
    C3 = (4 * M00 ** 3 +
          (-4 * M01 ** 2 - 4 * M02 ** 2 - 4 * M03 ** 2 -
           -4 * M10 ** 2 - 4 * M11 ** 2 - 4 * M12 ** 2 - 4 * M13 ** 2 -
           -4 * M20 ** 2 - 4 * M21 ** 2 - 4 * M22 ** 2 - 4 * M23 ** 2 -
           -4 * M30 ** 2 - 4 * M31 ** 2 - 4 * M32 ** 2 - 4 * M33 ** 2) * M00 +
          (8 * M10 * M11 + 8 * M20 * M21 + 8 * M30 * M31) * M01 +
          (8 * M10 * M12 + 8 * M20 * M22 + 8 * M30 * M32) * M02 +
          (8 * M10 * M13 + 8 * M20 * M23 + 8 * M30 * M33) * M03 +
          (8 * M22 * M33 - 8 * M23 * M32) * M11 +
          (-8 * M21 * M33 + 8 * M23 * M31) * M12 +
          8 * M13 * (M21 * M32 - M22 * M31))

    # Compute C4 for all matrices at once (this is the most complex one)
    C4 = (M00 ** 4 + M01 ** 4 + M02 ** 4 + M10 ** 4 +
          M11 ** 4 + M12 ** 4 + M20 ** 4 + M21 ** 4 +
          M22 ** 4 + M03 ** 4 + M13 ** 4 + M23 ** 4 +
          8 * M22 * M23 * M32 * M33 -
          8 * M30 * (M21 * M31 + M22 * M32 + M23 * M33) * M20 +
          8 * M31 * (M22 * M32 + M23 * M33) * M21 +
          8 * M13 * (M22 * M23 + M32 * M33) * M12 +
          (M30 ** 2 - M31 ** 2 - M32 ** 2 - M33 ** 2) ** 2 +
          (2 * M30 ** 2 - 2 * M31 ** 2 - 2 * M32 ** 2 + 2 * M33 ** 2) * M23 ** 2 +
          (2 * M23 ** 2 + 2 * M30 ** 2 - 2 * M31 ** 2 + 2 * M32 ** 2 - 2 * M33 ** 2) * M22 ** 2 +
          (2 * M22 ** 2 + 2 * M23 ** 2 + 2 * M30 ** 2 + 2 * M31 ** 2 - 2 * M32 ** 2 - 2 * M33 ** 2) * M21 ** 2 +
          (
                      -2 * M21 ** 2 - 2 * M22 ** 2 - 2 * M23 ** 2 + 2 * M30 ** 2 + 2 * M31 ** 2 + 2 * M32 ** 2 + 2 * M33 ** 2) * M20 ** 2 +
          (
                      2 * M20 ** 2 - 2 * M21 ** 2 - 2 * M22 ** 2 + 2 * M23 ** 2 + 2 * M30 ** 2 - 2 * M31 ** 2 - 2 * M32 ** 2 + 2 * M33 ** 2) * M13 ** 2 +
          (
                      2 * M13 ** 2 + 2 * M20 ** 2 - 2 * M21 ** 2 + 2 * M22 ** 2 - 2 * M23 ** 2 + 2 * M30 ** 2 - 2 * M31 ** 2 + 2 * M32 ** 2 - 2 * M33 ** 2) * M12 ** 2 +
          ((8 * M21 * M22 + 8 * M31 * M32) * M12 +
           8 * M13 * (M21 * M23 + M31 * M33)) * M11 +
          (
                      2 * M12 ** 2 + 2 * M13 ** 2 + 2 * M20 ** 2 + 2 * M21 ** 2 - 2 * M22 ** 2 - 2 * M23 ** 2 + 2 * M30 ** 2 + 2 * M31 ** 2 - 2 * M32 ** 2 - 2 * M33 ** 2) * M11 ** 2 +
          ((-8 * M20 * M21 - 8 * M30 * M31) * M11 + (-8 * M20 * M22 - 8 * M30 * M32) * M12 -
           8 * M13 * (M20 * M23 + M30 * M33)) * M10 +
          (
                      -2 * M11 ** 2 - 2 * M12 ** 2 - 2 * M13 ** 2 + 2 * M20 ** 2 + 2 * M21 ** 2 + 2 * M22 ** 2 + 2 * M23 ** 2 + 2 * M30 ** 2 + 2 * M31 ** 2 + 2 * M32 ** 2 + 2 * M33 ** 2) * M10 ** 2 +
          ((-8 * M21 * M32 + 8 * M22 * M31) * M10 +
           (8 * M20 * M32 - 8 * M22 * M30) * M11 +
           8 * M12 * (-M20 * M31 + M21 * M30)) * M03 +
          (
                      -2 * M10 ** 2 + 2 * M11 ** 2 + 2 * M12 ** 2 - 2 * M13 ** 2 - 2 * M20 ** 2 + 2 * M21 ** 2 + 2 * M22 ** 2 - 2 * M23 ** 2 - 2 * M30 ** 2 + 2 * M31 ** 2 + 2 * M32 ** 2 - 2 * M33 ** 2) * M03 ** 2 +
          ((-8 * M12 * M13 - 8 * M22 * M23 - 8 * M32 * M33) * M03 +
           (8 * M21 * M33 - 8 * M23 * M31) * M10 +
           (-8 * M20 * M33 + 8 * M23 * M30) * M11 -
           8 * M13 * (-M20 * M31 + M21 * M30)) * M02 +
          (
                      2 * M03 ** 2 - 2 * M10 ** 2 + 2 * M11 ** 2 - 2 * M12 ** 2 + 2 * M13 ** 2 - 2 * M20 ** 2 + 2 * M21 ** 2 - 2 * M22 ** 2 + 2 * M23 ** 2 - 2 * M30 ** 2 + 2 * M31 ** 2 - 2 * M32 ** 2 + 2 * M33 ** 2) * M02 ** 2 +
          ((-8 * M11 * M12 - 8 * M21 * M22 - 8 * M31 * M32) * M02 +
           (-8 * M11 * M13 - 8 * M21 * M23 - 8 * M31 * M33) * M03 +
           (-8 * M22 * M33 + 8 * M23 * M32) * M10 +
           (8 * M20 * M33 - 8 * M23 * M30) * M12 +
           8 * M13 * (-M20 * M32 + M22 * M30)) * M01 +
          (
                      2 * M02 ** 2 + 2 * M03 ** 2 - 2 * M10 ** 2 - 2 * M11 ** 2 + 2 * M12 ** 2 + 2 * M13 ** 2 - 2 * M20 ** 2 - 2 * M21 ** 2 + 2 * M22 ** 2 + 2 * M23 ** 2 - 2 * M30 ** 2 - 2 * M31 ** 2 + 2 * M32 ** 2 + 2 * M33 ** 2) * M01 ** 2 +
          ((8 * M10 * M11 + 8 * M20 * M21 + 8 * M30 * M31) * M01 +
           (8 * M10 * M12 + 8 * M20 * M22 + 8 * M30 * M32) * M02 +
           (8 * M10 * M13 + 8 * M20 * M23 + 8 * M30 * M33) * M03 +
           (8 * M22 * M33 - 8 * M23 * M32) * M11 +
           (-8 * M21 * M33 + 8 * M23 * M31) * M12 +
           8 * M13 * (M21 * M32 - M22 * M31)) * M00 +
          (-2 * M01 ** 2 - 2 * M02 ** 2 - 2 * M03 ** 2 - 2 * M10 ** 2 -
           2 * M11 ** 2 - 2 * M12 ** 2 - 2 * M13 ** 2 - 2 * M20 ** 2 -
           2 * M21 ** 2 - 2 * M22 ** 2 - 2 * M23 ** 2 - 2 * M30 ** 2 -
           2 * M31 ** 2 - 2 * M32 ** 2 - 2 * M33 ** 2) * M00 ** 2)

    if verbose and len(M_batch) == 1:  # Only print if single matrix and verbose requested
        print(f"C1: {C1[0]}")
        print(f"C2: {C2[0]}")
        print(f"C3: {C3[0]}")
        print(f"C4: {C4[0]}")

    # Return boolean array indicating physical realizability
    return (C1 >= 0) & (C2 >= 0) & (C3 >= 0) & (C4 >= 0)
